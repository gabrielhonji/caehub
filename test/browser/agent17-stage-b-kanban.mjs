import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)('/security/node_modules/@playwright/test');
const origin=process.env.CAEHUB_BROWSER_ORIGIN,evidence=process.env.CAEHUB_EVIDENCE_DIR;
if(!origin||!evidence||process.env.NODE_ENV!=='development')throw new Error('Disposable development origin and evidence directory are required');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'light',locale:'pt-BR'});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const api=async(path,method='GET',data)=>{const response=await page.request.fetch(`${origin}/api${path}`,{method,data});assert.ok(response.ok(),`${method} ${path}: ${response.status()} ${await response.text()}`);return response.status()===204?undefined:response.json();};
try{
  const foundation=await api('/foundation'),board=foundation.boards[0],suffix=Date.now(),title=`Kanban preenchido F8 ${suffix}`;
  const created=await api(`/boards/${board.id}/cards`,'POST',{title,description:'Descrição fictícia preenchida para inspeção',priority:'high',dueAt:'2027-06-15T15:00:00.000Z',dueOffsetMinutes:-180,tags:['f8','prioridade'],columnId:board.columns[0].id});
  await page.goto(`${origin}/#/espacos/${board.workspaceId}`);await page.locator(`[data-card-id="${created.id}"]`).waitFor();
  await page.evaluate(()=>scrollTo(0,0));
  const header=await page.locator('.site-header').boundingBox(),crumb=await page.locator('.breadcrumbs').first().boundingBox();
  assert.ok(header&&crumb&&header.y+header.height<=crumb.y,`O breadcrumb deve permanecer abaixo da navbar: header=${JSON.stringify(header)} crumb=${JSON.stringify(crumb)}`);
  assert.equal(await page.locator('#caehub-navigation a[aria-current="page"]').count(),1);
  await page.locator(`[data-card-id="${created.id}"] .card-detail-trigger`).click();
  let dialog=page.getByRole('dialog').filter({has:page.locator('.card-collaboration')});await dialog.waitFor();
  await dialog.getByRole('button',{name:'Adicionar item',exact:true}).click();
  await dialog.getByLabel('Novos itens').fill('Checklist fictício um, Checklist fictício dois');
  await dialog.getByRole('button',{name:'Adicionar',exact:true}).click();
  await dialog.getByLabel('Novo comentário').fill('Comentário fictício para a prova integrada.');
  await dialog.getByRole('button',{name:'Comentar',exact:true}).click();
  await dialog.getByText('Checklist fictício um',{exact:true}).waitFor();
  await dialog.getByText('Comentário fictício para a prova integrada.',{exact:true}).waitFor();
  await dialog.screenshot({path:`${evidence}/kanban-detalhe-preenchido-desktop-light.png`});
  await dialog.locator('details.card-administration>summary').click();
  await dialog.getByRole('button',{name:'Arquivar cartão',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Arquivados',exact:true}).click();
  const archive=page.getByRole('dialog',{name:'Cartões arquivados',exact:true});await archive.getByText(title,{exact:true}).waitFor();
  await archive.screenshot({path:`${evidence}/kanban-arquivo-preenchido-desktop-light.png`});
  const archivedCard=archive.locator('article').filter({hasText:title});
  await archivedCard.getByRole('button',{name:'Restaurar',exact:true}).click();
  await page.waitForTimeout(500);
  const afterRestore=await api(`/boards/${board.id}/archived-cards`);
  assert.equal(afterRestore.some(card=>card.id===created.id),false);
  assert.equal(await archive.getByText(title,{exact:true}).count(),0);
  await archive.getByText(title,{exact:true}).waitFor({state:'hidden',timeout:5000});
  await page.goto(`${origin}/?f8=${suffix}#/minhas-tarefas`);const taskLink=page.locator('.task-list a').filter({hasText:title});await taskLink.waitFor({timeout:5000});
  await page.screenshot({path:`${evidence}/minhas-tarefas-preenchida-desktop-light.png`,fullPage:true});
  await taskLink.click();
  await page.getByRole('heading',{name:title,exact:true}).waitFor();
  assert.equal(await page.getByRole('link',{name:'← Voltar às tarefas',exact:true}).count(),1);
  assert.equal(await page.getByRole('link',{name:'Abrir no espaço →',exact:true}).count(),1);
  assert.equal(await page.getByRole('button',{name:'Atualizar cartão',exact:true}).count(),1);
  await page.setViewportSize({width:390,height:844});await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:`${evidence}/kanban-cartao-mobile-dark.png`,fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.deepEqual(errors,[]);
  console.log('PASS Kanban filled card, priority, checklist/comment, archive/restore, task page and navigation geometry.');
}finally{await browser.close();}
